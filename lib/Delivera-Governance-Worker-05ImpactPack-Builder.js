/**
 * SSOT: Monthly Grow My Impact pack builder (deterministic markdown).
 */
import { readFile, writeFile, mkdir } from 'fs/promises';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { summarizeAdoptionMetrics } from './Delivera-Governance-Adoption-Metrics-IO.js';
import { readRecentJobs } from './Delivera-Governance-Worker-02Jobs-IO.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_DIR = join(__dirname, '..', 'data');

function monthKey(date = new Date()) {
  const d = date instanceof Date ? date : new Date(date);
  const y = d.getUTCFullYear();
  const m = String(d.getUTCMonth() + 1).padStart(2, '0');
  return `${y}-${m}`;
}

function impactFilePath(month) {
  return join(DATA_DIR, `Delivera-Impact-Pack-${month}.md`);
}

export async function impactPackExists(month) {
  try {
    await readFile(impactFilePath(month), 'utf8');
    return true;
  } catch (err) {
    return err?.code === 'ENOENT' ? false : false;
  }
}

/**
 * @param {object} [opts]
 * @returns {Promise<{ month, markdown, path, skipped }>}
 */
export async function buildImpactPack({ project = 'MPSA', month = null } = {}) {
  const m = month || monthKey();
  const path = impactFilePath(m);
  if (await impactPackExists(m)) {
    const existing = await readFile(path, 'utf8');
    return { month: m, markdown: existing, path, skipped: true };
  }

  const metrics = await summarizeAdoptionMetrics({ project });
  const jobs = await readRecentJobs({ project, limit: 50 });
  const briefJobs = jobs.filter((j) => j.type === 'prepare-weekly-brief' && j.status === 'completed');
  const nudgeJobs = jobs.filter((j) => j.type === 'prepare-nudges' && j.status === 'completed');

  const minutesSaved = metrics.byMetric?.reportingMinutesSaved;
  const avgMinutes = minutesSaved?.avg != null ? minutesSaved.avg : null;
  const confidence = metrics.byMetric?.leaderConfidence1to5;
  const avgConf = confidence?.avg != null ? confidence.avg : null;

  const lines = [];
  lines.push(`# Grow My Impact — ${project} — ${m}`);
  lines.push('');
  lines.push('## Delivery governance contribution');
  lines.push(`- Weekly briefs prepared (background): ${briefJobs.length}`);
  lines.push(`- Nudge preparation runs: ${nudgeJobs.length}`);
  lines.push(`- Adoption survey entries: ${metrics.total || 0}`);
  if (avgMinutes != null) lines.push(`- Avg reporting time saved (self-reported): ${avgMinutes} min/week`);
  if (avgConf != null) lines.push(`- Leader confidence (1–5 avg): ${avgConf}`);
  lines.push('');
  lines.push('## Vodacom priorities');
  lines.push('- **Customers:** Earlier risk visibility, fewer delivery surprises');
  lines.push('- **Simplicity:** Less manual status chasing; brief ready before meetings');
  lines.push('- **Growth:** Faster leadership decisions on blocked work');
  lines.push('- **Operational excellence:** Evidence-backed Jira governance');
  lines.push('');
  lines.push('## Evidence examples');
  for (const j of briefJobs.slice(0, 3)) {
    const risks = j.outputs?.riskCount ?? '—';
    lines.push(`- Brief ${j.completedAt?.slice(0, 10) || ''}: ${risks} risks surfaced, narrated by ${j.narratedBy || 'template'}`);
  }
  lines.push('');
  lines.push('_Generated by Delivera governance worker. Human-approved before external share._');

  const markdown = lines.join('\n');
  await mkdir(DATA_DIR, { recursive: true });
  await writeFile(path, markdown, 'utf8');
  return { month: m, markdown, path, skipped: false };
}

export { monthKey as impactPackMonthKey };
